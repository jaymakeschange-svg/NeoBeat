"""Embed the learned material files (materials/*.nbm, *.nbf) as Source/engine/MaterialData.h."""
import glob, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = ['// Generated by tools/gen_material_data.py from materials/ (MaterialLab, by Marbelite). Do not edit.',
       '#pragma once', '', '#include <string>', '', 'namespace nb', '{',
       '// each text is split into pieces (MSVC limits one string literal to 64 KB); join() puts it back together',
       'struct MaterialText { const char* id; const char* kind; const char* const* pieces;',
       '    std::string join() const { std::string s; for (auto p = pieces; *p != nullptr; ++p) s += *p; return s; } };', '']
entries = []
files = sorted(glob.glob(os.path.join(root, 'materials', '*.nbm'))) + sorted(glob.glob(os.path.join(root, 'materials', '*.nbf')))
for f in files:
    name = os.path.splitext(os.path.basename(f))[0]
    kind = 'body' if f.endswith('.nbm') else 'rubber'
    text = open(f).read()
    # MSVC limits a single string literal to ~16 KB: split into concatenated pieces
    pieces = [text[i:i + 12000] for i in range(0, len(text), 12000)]
    var = 'kMatPieces_' + name
    out.append(f'inline const char* const {var}[] = {{')
    out += [f'    R"NBMAT({p})NBMAT",' for p in pieces]
    out.append('    nullptr };')
    entries.append(f'    {{ "{name}", "{kind}", {var} }},')
out += ['', 'inline const MaterialText kMaterialTexts[] = {'] + entries + ['};', f'constexpr int kNumMaterialTexts = {len(files)};', '} // namespace nb', '']
open(os.path.join(root, 'Source', 'engine', 'MaterialData.h'), 'w').write('\n'.join(out))
print(len(files), 'materials embedded')

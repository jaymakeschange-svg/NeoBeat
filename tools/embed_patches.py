#!/usr/bin/env python3
"""Embed every patch text into Source/engine/PatchData.h, so the plugin carries
its whole sound library with no files to install. Run after editing patches/."""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORDER = [('round4', sorted(os.listdir(os.path.join(ROOT, 'patches', 'round4')))),
         ('round5', sorted(os.listdir(os.path.join(ROOT, 'patches', 'round5')))),
         ('lab', sorted(os.listdir(os.path.join(ROOT, 'patches', 'lab'))))]

out = ['// Generated by tools/embed_patches.py from patches/ -- do not edit by hand.',
       '#pragma once', '', 'namespace nb', '{', 'struct PatchText { const char* id; const char* text; };', '',
       'inline const PatchText kPatchTexts[] = {']
count = 0
for folder, files in ORDER:
    for f in files:
        if not f.endswith('.txt'):
            continue
        text = open(os.path.join(ROOT, 'patches', folder, f)).read()
        assert ')NBPATCH"' not in text
        out.append(f'    {{ "{folder}/{f[:-4]}", R"NBPATCH({text})NBPATCH" }},')
        count += 1
out += ['};', f'constexpr int kNumPatchTexts = {count};', '} // namespace nb', '']
open(os.path.join(ROOT, 'Source', 'engine', 'PatchData.h'), 'w').write('\n'.join(out))
print(f'embedded {count} patches')
